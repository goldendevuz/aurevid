# Regenerates THIRD_PARTY_LICENSES.md from what is actually installed (runtime deps only).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/THIRD_PARTY_LICENSES.md"
{
  echo "# Third-party licenses"
  echo
  echo "Generated by \`scripts/licenses.sh\` from installed packages (runtime dependencies only)."
  echo "Re-run after changing dependencies. Review any license that is not permissive."
  echo
  cat "$root/scripts/license-review.md"
  echo
  echo "## Backend (Python)"
  echo
  cd "$root/backend"
  uv sync --frozen --no-dev -q
  uv run --no-sync python -I "$root/scripts/py_licenses.py"
  uv sync --frozen -q
  echo
  echo "## Frontend (npm, production dependencies)"
  echo
  cd "$root/frontend"
  echo "| Name | Version | License |"
  echo "|------|---------|---------|"
  npm ls --omit=dev --all --parseable 2>/dev/null | tail -n +2 | sort -u | while read -r dir; do
    node -e 'const p=require(process.argv[1]+"/package.json");const l=typeof p.license==="string"?p.license:(p.license&&p.license.type)||"UNKNOWN";console.log(`| ${p.name} | ${p.version} | ${l} |`)' "$dir"
  done | sort -u
} > "$out"
echo "wrote $out"
